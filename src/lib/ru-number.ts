// Число прописью — только для текстов главной: «и ещё десять марок».
//
// Цифра в такой фразе читается как счётчик товара («и ещё 10 марок»), а
// текст первого экрана — речь, а не таблица. Словарь маленький намеренно:
// марок у салона полтора десятка, и на большее он не понадобится. Выйдет за
// пределы — вернётся цифра, это лучше, чем падение сборки.
const WORDS = [
  "ноль", "одна", "две", "три", "четыре", "пять", "шесть", "семь", "восемь",
  "девять", "десять", "одиннадцать", "двенадцать", "тринадцать",
  "четырнадцать", "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать",
  "девятнадцать", "двадцать",
];

export function numberWord(n: number): string {
  return WORDS[n] ?? String(n);
}
